"""data/db/*.json + tags_seed.json  ->  data/seed.sql  (safe to run many times).

Loads the fixed tag list, the scraped opportunities (upsert by source_url) and their tags.
Run it against the project with the Supabase CLI (the CLI's own login, no password needed):

    python seed_sql.py
    npx supabase db query --linked -f data/seed.sql

Re-running updates the rows in place and removes scraped rows that are no longer in the files.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "data" / "seed.sql"

# Every column we write, in order (id, created_at, search_vector are generated by the DB).
COLS = [
    "type", "organizer_id", "title", "description", "image_url", "external_url", "city",
    "is_online", "audience", "starts_at", "ends_at", "deadline_at", "status", "source", "source_url",
]


def lit(v) -> str:
    """One value as an SQL literal."""
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    return "'" + str(v).replace("'", "''") + "'"


def main() -> None:
    sys.stdout.reconfigure(encoding="utf-8")
    tags = json.loads((HERE / "tags_seed.json").read_text(encoding="utf-8"))
    rows = []
    for f in sorted((HERE / "data" / "db").glob("*.json")):
        rows += json.loads(f.read_text(encoding="utf-8"))

    sql = ["-- Generated by seed_sql.py. Do not edit by hand.", "begin;", ""]
    sql.append("insert into public.tags (slug, name) values")
    sql.append(",\n".join(f"  ({lit(t['slug'])}, {lit(t['name'])})" for t in tags))
    sql.append("on conflict (slug) do update set name = excluded.name;\n")

    # Mirror the files: scraped rows that are no longer in them are removed
    # (organizer posts are never touched; their tag links go with them by cascade).
    keep = ", ".join(lit(r["source_url"]) for r in rows)
    sql.append(f"delete from public.opportunities where source = 'scraper' and source_url not in ({keep});\n")

    updates = ", ".join(f"{c} = excluded.{c}" for c in COLS if c != "source_url")
    for r in rows:
        vals = ", ".join(
            lit(r[c]) if c not in ("type", "audience", "status", "source") else lit(r[c]) + f"::public.{ {'type': 'opportunity_type', 'audience': 'audience', 'status': 'opportunity_status', 'source': 'opportunity_source'}[c] }"
            for c in COLS
        )
        sql.append(
            f"insert into public.opportunities ({', '.join(COLS)}) values ({vals})\n"
            f"on conflict (source_url) do update set {updates};"
        )
        slugs = ", ".join(lit(s) for s in r["tags"])
        sql.append(f"delete from public.opportunity_tags where opportunity_id = (select id from public.opportunities where source_url = {lit(r['source_url'])});")
        if r["tags"]:
            sql.append(
                "insert into public.opportunity_tags (opportunity_id, tag_id)\n"
                f"select o.id, t.id from public.opportunities o, public.tags t\n"
                f"where o.source_url = {lit(r['source_url'])} and t.slug in ({slugs});"
            )
    sql += ["", "commit;", ""]
    OUT.write_text("\n".join(sql), encoding="utf-8")
    print(f"{len(tags)} tags, {len(rows)} opportunities -> {OUT}")


if __name__ == "__main__":
    main()
